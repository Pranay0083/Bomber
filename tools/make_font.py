def write_png(path, width, height, rows):
    raw = b"".join(b"\x00" + bytes(channel for pixel in row for channel in pixel) for row in rows)

    def chunk(kind, data):
        body = kind + data
        return struct.pack(">I", len(data)) + body + struct.pack(">I", zlib.crc32(body) & 0xFFFFFFFF)

    header = struct.pack(">IIBBBBB", width, height, 8, 6, 0, 0, 0)
    path.write_bytes(b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", header)
                     + chunk(b"IDAT", zlib.compress(raw, 9)) + chunk(b"IEND", b""))


def main():
    names = list(GLYPHS)
    sheet_rows = (len(names) + COLUMNS - 1) // COLUMNS
    width, height = COLUMNS * CELL, sheet_rows * CELL
    pixels = [[(0, 0, 0, 0)] * width for _ in range(height)]
    chars = []
    for index, name in enumerate(names):
        glyph = GLYPHS[name]
        assert len(glyph) == HEIGHT, name
        glyph_width = len(glyph[0])
        assert all(len(row) == glyph_width for row in glyph), name
        left, top = (index % COLUMNS) * CELL, (index // COLUMNS) * CELL
        for y, row in enumerate(glyph):
            for x, char in enumerate(row):
                if char == "#":
                    pixels[top + y][left + x] = (255, 255, 255, 255)
        codes = [ord(name)]
        if name.isalpha():
            codes.append(ord(name.lower()))
        for code in codes:
            chars.append(f"char id={code} x={left} y={top} width={glyph_width} height={HEIGHT} "
                         f"xoffset=0 yoffset=0 xadvance={glyph_width + 1} page=0 chnl=0")
    chars.append("char id=32 x=0 y=0 width=0 height=0 xoffset=0 yoffset=0 xadvance=3 page=0 chnl=0")

    write_png(OUT / "font.png", width, height, pixels)
    lines = [
        'info face="BlastPixel" size=7 bold=0 italic=0 charset="" unicode=1 stretchH=100 smooth=0 aa=1 '
        'padding=0,0,0,0 spacing=1,1',
        f"common lineHeight=9 base=7 scaleW={width} scaleH={height} pages=1 packed=0",
        'page id=0 file="font.png"',
        f"chars count={len(chars)}",
    ] + chars
    (OUT / "font.fnt").write_text("\n".join(lines) + "\n")
    print(f"Wrote {len(names)} glyphs to {OUT / 'font.png'}")


if __name__ == "__main__":
    main()
